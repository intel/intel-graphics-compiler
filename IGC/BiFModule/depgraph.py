"""Builds the dependency graph of the BiF modules, see BiFManager/README.md.

usage: depgraph.py <symbols.json> --header <OCLBiFImpl.h> --order <modules.txt>
                   --shared-globals <globals.txt>

A module depends on the modules that define what it declares. Writes the
package order of the modules, the graphs and the built-in name hashes for
BiFManagerHandler.cpp, and the globals used across modules.
"""

import argparse
import json
import sys


def name_hash(name):
    """64-bit FNV-1a, as getHash() in BiFManagerCommon.cpp."""
    h = 0xCBF29CE484222325
    for byte in name.encode():
        h = ((h ^ byte) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def build_graph(modules, nodes):
    """Edges of the graph over the given modules, and the defining module by symbol."""
    definer = {}
    for idx in nodes:
        m = modules[idx]
        for sym in m["defined_functions"] + m["defined_globals"]:
            if sym in definer and definer[sym] != idx:
                sys.exit(f"depgraph.py: {sym} is defined by {modules[definer[sym]]['path']} and {m['path']}")
            definer[sym] = idx
    deps = {}
    for idx in nodes:
        m = modules[idx]
        used = m["declared_functions"] + m["declared_globals"]
        deps[idx] = sorted({definer[sym] for sym in used if sym in definer} - {idx})
    return deps, definer


def topological_order(deps):
    """Nodes with their dependencies first; (None, cycle) if the graph has a cycle."""
    order, state = [], {}
    for root in sorted(deps):
        if root in state:
            continue
        # iterative DFS; state 1 = on the stack, 2 = done
        stack = [(root, iter(deps[root]))]
        state[root] = 1
        while stack:
            node, it = stack[-1]
            nxt = next(it, None)
            if nxt is None:
                stack.pop()
                state[node] = 2
                order.append(node)
            elif state.get(nxt) == 1:
                path = [n for n, _ in stack]
                return None, path[path.index(nxt):] + [nxt]
            elif nxt not in state:
                state[nxt] = 1
                stack.append((nxt, iter(deps[nxt])))
    return order, None


def check_acyclic(modules, deps, label):
    _, cycle = topological_order(deps)
    if cycle:
        names = " -> ".join(modules[idx]["path"] for idx in cycle)
        sys.exit(f"depgraph.py: the {label} modules depend on each other in a cycle: {names}")


def write_array(out, decl, values):
    out.write(f"\n{decl} = {{")
    for i, v in enumerate(values):
        out.write(("\n    " if i % 8 == 0 else " ") + f"{v},")
    out.write("\n};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("symbols")
    ap.add_argument("--header", required=True)
    ap.add_argument("--order", required=True)
    ap.add_argument("--shared-globals", required=True)
    a = ap.parse_args()

    with open(a.symbols) as f:
        modules = json.load(f)["modules"]
    main_nodes = [i for i, m in enumerate(modules) if m["kind"] == "main"]
    graphs = {}
    for bits in (32, 64):
        nodes = main_nodes + [i for i, m in enumerate(modules) if m["kind"] == f"size{bits}"]
        deps, definer = build_graph(modules, nodes)
        check_acyclic(modules, deps, f"{bits}-bit")
        graphs[bits] = (deps, definer)

    # Main modules first, then size32 and size64, each in topological order.
    # The handler loads all needed modules before linking, so no other order is required.
    order = []
    for kind, bits in (("main", 64), ("size32", 32), ("size64", 64)):
        deps = graphs[bits][0]
        kind_deps = {i: [d for d in deps[i] if modules[d]["kind"] == kind] for i in deps if modules[i]["kind"] == kind}
        order += reversed(topological_order(kind_deps)[0])
    position = {idx: pos for pos, idx in enumerate(order)}

    with open(a.order, "w") as f:
        for idx in order:
            f.write(modules[idx]["path"] + "\n")

    shared = set()
    for deps, definer in graphs.values():
        for idx in deps:
            for sym in modules[idx]["declared_globals"]:
                if sym in definer and definer[sym] != idx:
                    shared.add(sym)
    with open(a.shared_globals, "w") as f:
        for sym in sorted(shared):
            f.write(sym + "\n")

    with open(a.header, "w") as out:
        out.write("// Generated by depgraph.py from the BiF modules.\n")
        for bits in (32, 64):
            first = next(position[i] for i in order if modules[i]["kind"] == f"size{bits}")
            out.write(f"const int Module{bits}Idx = {first};\n")
        for bits in (32, 64):
            deps, definer = graphs[bits]
            # Module i depends on ModuleDeps[ModuleDepsBegin[i] .. ModuleDepsBegin[i + 1]);
            # modules of the other pointer size have no dependencies.
            begin, flat = [], []
            for pos in range(len(order)):
                begin.append(len(flat))
                flat += sorted(position[d] for d in deps.get(order[pos], []))
            begin.append(len(flat))
            write_array(out, f"static const int ModuleDepsBegin{bits}[]", begin)
            # Arrays cannot be empty.
            write_array(out, f"static const int ModuleDeps{bits}[]", flat + [-1])
            funcs = {}
            for idx in deps:
                for sym in modules[idx]["defined_functions"]:
                    h = name_hash(sym)
                    if h in funcs and funcs[h][1] != position[idx]:
                        sys.exit(f"depgraph.py: {sym} and {funcs[h][0]} have the same hash")
                    funcs[h] = (sym, position[idx])
            hashes = sorted(funcs)
            write_array(out, f"static const uint64_t FuncHash{bits}[]", [f"{h}ULL" for h in hashes])
            write_array(out, f"static const int FuncModule{bits}[]", [funcs[h][1] for h in hashes])


if __name__ == "__main__":
    main()
