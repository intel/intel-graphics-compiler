import hashlib
import os
import sys


def PrintHelp():
    sys.stdout.write('Usage: {0} <input file> <output file>\n'.format(os.path.basename(__file__)))
    sys.stdout.write('\n')
    sys.stdout.write('    <input file>  - Path to the generated CTHeader.h (opencl_cth.h) to hash.\n')
    sys.stdout.write('    <output file> - Path to output .cpp file that will define CTHeaderId.\n')


def main(argv):
    if len(argv) != 3:
        PrintHelp()
        return 1

    inputFile, outputFile = argv[1], argv[2]

    try:
        with open(inputFile, 'rb') as f:
            data = f.read()
    except EnvironmentError as ex:
        sys.stderr.write('ERROR: Cannot open input file "{0}".\n       {1}.\n'.format(inputFile, ex.strerror))
        return 1

    digest = hashlib.sha256(data).hexdigest()

    try:
        with open(outputFile, 'w') as f:
            f.write('// This file is auto generated by header_id_gen.py, DO NOT EDIT\n\n')
            f.write('extern "C" const char CTHeaderId[] = "{0}";\n'.format(digest))
    except EnvironmentError as ex:
        sys.stderr.write('ERROR: Cannot create/open output file "{0}".\n       {1}.\n'.format(outputFile, ex.strerror))
        return 1

    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
